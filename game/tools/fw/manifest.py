# Frozen-module manifest for the Long Voyage game firmware (tools/build_firmware.sh).
# Paths are relative to this file. Everything frozen runs from flash: code and constant
# data cost no heap. Per-board settings stay on the filesystem (/data/ship.json, written
# by the web updater or by hand) and are never frozen.

# The board's own manifest first: networking, aioble, asyncio, _boot.py (filesystem).
include("$(BOARD_DIR)/manifest.py")

# The game core (lv/: record, chlog, pack, state, engine, ops, prng, clock, led, engage,
# codes, sync, ble) and the ship runtime (board/).
package("lv", base_path="../..")
module("lvship.py", base_path="../../board")
module("lvwifi.py", base_path="../../board")
module("selftest.py", base_path="../../board")

# Generated by gen_lvdata.py into build/fw/: lvdata.py (pack.bin and the phone's gzipped
# app.html, text.json and engage.json as bytes constants) and lvmain.py (board/main.py).
module("lvdata.py", base_path="../../build/fw")
module("lvmain.py", base_path="../../build/fw")

# boot.py: on a fresh filesystem, writes a one-line /main.py ("import lvmain") so the
# board starts the game after a drag-and-drop flash. It never overwrites a main.py.
module("boot.py", base_path=".")
