#!/usr/bin/env python3
"""Writes build/fw/lvfrozen.py: the game firmware's version manifest (frozen with it).

  ID        "lv-core"
  VERSION   lv.VERSION of the frozen package
  CORE      first 12 hex of sha256 over everything frozen (path + bytes, in a fixed order):
            the game core lv/*.py, the board modules board/<BOARD>.py, the story pack
            build/pack.bin and tools/fw/lvfrozen_rt.py. Partial updater releases name the
            CORE they were built against.
  MODULES   the frozen lv modules ("lv" is the package itself)
  BOARD     the frozen board modules (lvship, lvweb, lvphone, ... selftest; since 0.2.0)
  PACK      first 12 hex of the frozen pack's sha256 (lvpackdata.DATA), or None
  MICROPYTHON  the MicroPython it was built on

followed by tools/fw/lvfrozen_rt.py (the lvx/ override loader, firmware(), describe()),
frozen too so it costs no heap. Also writes:
  build/fw/lvpackdata.py   DATA = b"..." (build/pack.bin as a frozen bytes object: read in
                           place from flash, so the pack costs no heap; lvship.pack_for)
  build/fw/lvfrozen.json   the same plus each frozen file's sha256 ("lv.<name>", "<board
                           module>", "pack.bin"), so a later build can tell what changed
                           since this core and ship only that: a core module as an lvx/
                           override, a board module as /<name>.mpy, the pack as /pack.bin,
                           each found before the frozen one (tools/fw/changed_modules.py,
                           tools/board_build.sh FROZEN_CORE=..., build_release.py --frozen).
lv.firmware() / lv.describe() call it; selftest and the updater page report it as
"frozen lv-core <VERSION> (core <CORE>), overrides: [...]" (plus the board files that
replace frozen board modules, if any).
  python3 tools/fw/gen_lvfrozen.py [--print-core | --print-board]
"""
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "build", "fw")
MICROPYTHON = "v1.29.0"


# The board modules frozen since lv-core 0.2.0 (top-level modules, from board/). main.py
# and boot.py stay files: they are the boot entries, and they are tiny. lvota, lvsig and
# lvboot (over-the-air updates), lvfunnel (the home-screen funnel), lvcode (Change your
# code), lvledtest (Test light) and lvsafe (safe mode and the fault notes) came after
# lv-core 0.2.0: on that core they ship as .mpy. tools/board_build.sh, the manifest
# (tools/fw/manifest.py) and the tests take the list from here.
BOARD = ("lvship", "lvreport", "lvcal", "lvled", "lvledcfg", "lvbatt", "lvdays", "lvweb",
         "lvphone", "lvstat", "lvwifi", "selftest", "lvota", "lvsig", "lvboot",
         "lvfunnel", "lvcode", "lvledtest", "lvsafe")
PACK = os.path.join(ROOT, "build", "pack.bin")


def frozen_sources():
    d = os.path.join(ROOT, "lv")
    return sorted(f for f in os.listdir(d) if f.endswith(".py"))


RT = os.path.join(ROOT, "tools", "fw", "lvfrozen_rt.py")


def frozen_files():
    """[(key, path)] of everything frozen, in hash order: "lv.<name>" ("lv" for the package),
    then the board modules by name, then "pack.bin"."""
    out = [("lv" if f == "__init__.py" else "lv." + f[:-3], os.path.join(ROOT, "lv", f))
           for f in frozen_sources()]
    out += [(m, os.path.join(ROOT, "board", m + ".py")) for m in BOARD]
    out.append(("pack.bin", PACK))
    return out


def _rd(path):
    with open(path, "rb") as f:
        return f.read()


def core_hash():
    if not os.path.exists(PACK):
        sys.exit("gen_lvfrozen: %s missing: run tools/lvc.py first" % PACK)
    h = hashlib.sha256()
    for f in frozen_sources():
        h.update(("lv/" + f + "\n").encode())
        h.update(_rd(os.path.join(ROOT, "lv", f)))
    for m in BOARD:
        h.update(("board/" + m + ".py\n").encode())
        h.update(_rd(os.path.join(ROOT, "board", m + ".py")))
    h.update(b"pack.bin\n")
    h.update(_rd(PACK))
    h.update(b"lvfrozen_rt.py\n")
    h.update(_rd(RT))
    return h.hexdigest()[:12]


def main(argv):
    if "--print-board" in argv:
        print(" ".join(BOARD))
        return
    core = core_hash()
    if "--print-core" in argv:
        print(core)
        return
    version = re.search(r'^VERSION = "([^"]+)"', open(os.path.join(ROOT, "lv", "__init__.py")).read(), re.M).group(1)
    mods = ["lv" if f == "__init__.py" else "lv." + f[:-3] for f in frozen_sources()]
    pack = _rd(PACK)
    pack_sha = hashlib.sha256(pack).hexdigest()
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "lvfrozen.py"), "w") as f:
        f.write("# Generated by tools/fw/gen_lvfrozen.py: what this game firmware froze in.\n")
        f.write("ID = %r\nVERSION = %r\nCORE = %r\nMICROPYTHON = %r\nMODULES = %r\nBOARD = %r\nPACK = %r\n" % (
            "lv-core", version, core, MICROPYTHON, tuple(mods), BOARD, pack_sha[:12]))
        f.write("\n" + open(RT).read())
    with open(os.path.join(OUT, "lvpackdata.py"), "w") as f:
        f.write("# Generated by tools/fw/gen_lvfrozen.py from build/pack.bin (sha256 %s).\n"
                "# Frozen: a bytes object in flash, read in place (lvship.pack_for). A /pack.bin file\n"
                "# on the board is used instead when there is one (a pack update without reflashing).\n"
                % pack_sha)
        f.write("DATA = %r\n" % pack)
    shas = {k: hashlib.sha256(_rd(p)).hexdigest() for k, p in frozen_files()}
    with open(os.path.join(OUT, "lvfrozen.json"), "w") as f:
        json.dump({"id": "lv-core", "version": version, "core": core, "micropython": MICROPYTHON,
                   "modules": mods, "board": list(BOARD), "pack": "pack.bin", "sha256": shas},
                  f, indent=1, sort_keys=True)
        f.write("\n")
    print("lvfrozen: lv-core %s, core %s, %d lv modules, %d board modules, pack %d B" % (
        version, core, len(mods), len(BOARD), len(pack)))


if __name__ == "__main__":
    main(sys.argv[1:])
