#!/usr/bin/env python3
"""Writes build/fw/lvdata.py and build/fw/lvmain.py for the frozen firmware (manifest.py).

lvdata.py holds bytes constants, frozen into flash: read in place, they cost no heap.
  VERSION   lvship.VERSION these were built with (lvship uses PACK only on a match)
  PACK      build/pack.bin
  ASSETS    {path: (gzip bytes, content type)} for the phone: app.html, text.json,
            engage.json, ready for the phone game server to send as they are
Run from game/ after tools/lvc.py, tools/lve.py and web/build.py.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "build", "fw")


def rd(name):
    with open(os.path.join(ROOT, "build", name), "rb") as f:
        return f.read()


def main():
    os.makedirs(OUT, exist_ok=True)
    src = open(os.path.join(ROOT, "board", "lvship.py")).read()
    version = re.search(r'^VERSION = "([^"]+)"', src, re.M).group(1)
    assets = (("/app.html", "app.html.gz", "text/html; charset=utf-8"),
              ("/text.json", "text.json.gz", "application/json"),
              ("/engage.json", "engage.json.gz", "application/json"))
    lines = ["# Generated by tools/fw/gen_lvdata.py for the frozen firmware. Do not edit.",
             "VERSION = %r" % version,
             "PACK = %r" % rd("pack.bin"),
             "ASSETS = {"]
    total = len(rd("pack.bin"))
    for path, name, ctype in assets:
        b = rd(name)
        total += len(b)
        lines.append("    %r: (%r, %r)," % (path, b, ctype))
    lines.append("}")
    with open(os.path.join(OUT, "lvdata.py"), "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(ROOT, "board", "main.py")) as f:
        main_src = f.read()
    with open(os.path.join(OUT, "lvmain.py"), "w") as f:
        f.write("# Frozen copy of board/main.py (tools/fw/gen_lvdata.py).\n" + main_src)
    print("lvdata: version %s, %d B of frozen data (pack + gzipped app.html, text.json, engage.json)"
          % (version, total))


if __name__ == "__main__":
    main()
